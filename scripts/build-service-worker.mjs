import { createHash } from 'node:crypto'
import { readFile, readdir, stat, writeFile } from 'node:fs/promises'
import { resolve, relative, sep } from 'node:path'

const siteRoot = resolve(process.env.SITE_OUT_DIR ?? 'dist/site')
const release = process.env.VITE_DOCS_BUILD_MARKER ?? 'release'
const indexFile = resolve(siteRoot, 'index.html')
await writeFile(indexFile, (await readFile(indexFile, 'utf8')).replace('__DOCS_RELEASE__', release))

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const files = await Promise.all(entries.map(async entry => {
    const file = resolve(directory, entry.name)
    return entry.isDirectory() ? walk(file) : [file]
  }))
  return files.flat()
}

const emitted = (await walk(resolve(siteRoot, 'assets')))
  .filter(file => !file.endsWith('.map'))
  .map(file => `/${relative(siteRoot, file).split(sep).join('/')}`)
  .sort()
const shell = ['/', '/index.html', '/offline.html', '/privacy/', '/terms/', '/favicon.svg', '/icon-192.svg', '/icon-512.svg', '/manifest.webmanifest', '/riso-scheduler.webp', ...emitted]
const revisionHash = createHash('sha256')
for (const url of shell.filter(url => url !== '/')) {
  const file = url.endsWith('/') ? `${url.slice(1)}index.html` : url.slice(1)
  revisionHash.update(await readFile(resolve(siteRoot, file)))
}
const revision = revisionHash.digest('hex').slice(0, 16)
const worker = `/* Generated by scripts/build-service-worker.mjs. Do not edit. */
const CACHE_PREFIX = 'headless-scheduler-docs-'
const CACHE = '${`headless-scheduler-docs-${revision}`}'
const PRECACHE = ${JSON.stringify(shell)}

self.addEventListener('install', event => event.waitUntil((async () => {
  const cache = await caches.open(CACHE)
  // Query each source by revision before storing it under its stable shell URL.
  // That prevents the old worker from satisfying a new worker's install with stale cache hits.
  await Promise.all(PRECACHE.map(async url => {
    const separator = url.includes('?') ? '&' : '?'
    const response = await fetch(url + separator + '__hs_precache=' + CACHE, { cache: 'reload' })
    if (!response.ok) throw new Error('Precache failed: ' + url)
    await cache.put(url, response)
  }))
  await self.skipWaiting()
})()))

self.addEventListener('activate', event => event.waitUntil((async () => {
  const keys = await caches.keys()
  await Promise.all(keys.filter(key => key.startsWith(CACHE_PREFIX) && key !== CACHE).map(key => caches.delete(key)))
  await self.clients.claim()
})()))

self.addEventListener('message', event => {
  if (event.data === 'headless-scheduler-cache-version') event.ports[0]?.postMessage({ cache: CACHE })
})

self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET') return
  if (event.request.cache === 'reload') return
  const url = new URL(event.request.url)
  if (url.origin !== self.location.origin) return
  const currentCache = request => caches.open(CACHE).then(cache => cache.match(request))
  if (url.pathname.startsWith('/api/')) {
    event.respondWith(fetch(event.request).catch(() => currentCache(event.request)))
    return
  }
  if (event.request.mode === 'navigate') {
    // Documentation HTML is intentionally network-first. During a worker
    // hand-off a navigation can still be dispatched to the previously active
    // worker; letting that worker answer from its stable /index.html cache
    // would paint the old release in a brand-new tab. The cached shell remains
    // the offline fallback, so the app still opens without a connection.
    event.respondWith(fetch(event.request).catch(() => currentCache('/index.html').then(hit => hit || currentCache('/offline.html'))))
    return
  }
  event.respondWith(currentCache(event.request).then(hit => hit || fetch(event.request)))
})

`

await stat(siteRoot)
await writeFile(resolve(siteRoot, 'sw.js'), worker)
console.log(JSON.stringify({ serviceWorker: 'sw.js', release, revision, precache: shell.length }))
